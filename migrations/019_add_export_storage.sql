-- Purpose: Store completed reveal export videos in cloud storage

-- Create storage bucket for exports (private)
-- Only service_role can access directly
INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
VALUES (
  'exports',
  'exports',
  false,  -- Private bucket
  524288000,  -- 500 MB limit per file
  ARRAY['video/mp4']
)
ON CONFLICT (id) DO NOTHING;

-- Storage policies: Service role only
-- Application enforces authorization via signed URLs
-- No public access allowed

-- Grant service_role full access to bucket
-- (Service role bypasses RLS by default, but explicit policies are clearer)
CREATE POLICY "Service role full access"
ON storage.objects
FOR ALL
TO service_role
USING (bucket_id = 'exports');

-- No public access policies
-- Downloads use short-lived signed URLs generated by application

